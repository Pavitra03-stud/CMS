/* =========================================================
   HELPERS
========================================================= */

/*
  Gemini may return either:
  - normal strings
  - Portable Text arrays

  This helper allows the preview to safely display both.
*/
const getText = (value) => {
  if (value === null || value === undefined) {
    return "";
  }

  if (typeof value === "string") {
    return value;
  }

  if (typeof value === "number") {
    return String(value);
  }

  if (Array.isArray(value)) {
    return value
      .map((block) => {
        if (typeof block === "string") {
          return block;
        }

        if (block?.children && Array.isArray(block.children)) {
          return block.children
            .map((child) => child?.text || "")
            .join("");
        }

        return "";
      })
      .join("\n");
  }

  return "";
};


/*
  Safely extract a URL.
*/
const getUrl = (value) => {
  if (!value) {
    return "";
  }

  if (typeof value === "string") {
    return value;
  }

  return "";
};


/*
  Convert markdown-style links generated by AI into
  normal readable text for the preview.
*/
const cleanText = (value) => {
  const text = getText(value);

  return text
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, "$1")
    .replace(/\\n/g, "\n")
    .trim();
};


/*
  Safely create a color.
*/
const safeColor = (value, fallback) => {
  if (!value || typeof value !== "string") {
    return fallback;
  }

  return value;
};


/*
  Safely create an image URL.
*/
const safeImage = (value) => {
  if (!value || typeof value !== "string") {
    return "";
  }

  return value;
};


