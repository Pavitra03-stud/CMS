/* =========================================================
   NAVIGATION PREVIEW
========================================================= */

function PreviewNavigation({
  navigation,
}) {
  if (!navigation) {
    return null;
  }


  const menuItems =
    Array.isArray(
      navigation.menuItems
    )
      ? navigation.menuItems.filter(
          (item) =>
            item?.show !== false
        )
      : [];


  return (
    <nav
      style={{
        ...styles.cmsNavbar,

        background:
          safeColor(
            navigation.backgroundColor,
            "#111827"
          ),

        color:
          safeColor(
            navigation.textColor,
            "#ffffff"
          ),
      }}
    >

      {/* SITE TITLE */}

      <div
        style={
          styles.cmsSiteTitle
        }
      >
        {cleanText(
          navigation.siteTitle
        ) || "My Website"}
      </div>


      {/* MENU */}

      <div
        style={
          styles.cmsNavLinks
        }
      >

        {menuItems.map(
          (item, index) => (

            <a
              key={
                item?._key ||
                index
              }
              href={
                item?.link ||
                "#"
              }
              style={{
                ...styles.cmsNavLink,

                color:
                  safeColor(
                    navigation.textColor,
                    "#ffffff"
                  ),
              }}
              onClick={(e) => {
                const link =
                  item?.link || "";

                if (
                  link.startsWith("#")
                ) {
                  e.preventDefault();

                  const target =
                    document.querySelector(
                      link
                    );

                  if (target) {
                    target.scrollIntoView({
                      behavior:
                        "smooth",
                    });
                  }
                }
              }}
            >
              {cleanText(
                item?.label
              )}
            </a>

          )
        )}

      </div>

    </nav>
  );
}


/* =========================================================
   HERO PREVIEW
========================================================= */

function PreviewHero({
  hero,
}) {
  if (!hero) {
    return null;
  }


  if (
    hero.showSection === false
  ) {
    return null;
  }


  const image =
    safeImage(
      hero.imageUrl ||
      hero.heroImage
    );


  const buttons =
    Array.isArray(
      hero.buttons
    )
      ? hero.buttons
      : [];


  const backgroundColor =
    safeColor(
      hero.backgroundColor,
      "#111827"
    );


  const textColor =
    safeColor(
      hero.textColor,
      "#ffffff"
    );


  return (
    <section
      id="home"
      style={{
        ...styles.cmsHero,

        backgroundColor:
          backgroundColor,

        color:
          textColor,

        backgroundImage:
          hero.useBackgroundImage &&
          hero.heroBackground
            ? `url(${hero.heroBackground})`
            : "none",

        backgroundSize:
          hero.backgroundSize ||
          "cover",

        backgroundPosition:
          hero.backgroundPosition ||
          "center",
      }}
    >

      {/* OVERLAY */}

      {hero.showOverlay &&
        hero.heroBackground && (
          <div
            style={{
              ...styles.heroOverlay,

              background:
                hero.overlayColor ||
                "rgba(0,0,0,0.35)",
            }}
          />
        )}


      <div
        style={{
          ...styles.heroContent,

          textAlign:
            hero.textAlign ||
            "center",

          position: "relative",

          zIndex: 2,
        }}
      >

        {/* IMAGE */}

        {image && (
          <img
            src={image}
            alt=""
            style={{
              ...styles.heroImage,

              borderRadius:
                hero.imageShape ===
                "circle"
                  ? "50%"
                  : hero.imageShape ===
                    "diamond"
                  ? "25%"
                  : "18px",

              width: "150px",
              height: "150px",
              objectFit: "cover",

              transform:
                hero.imageShape ===
                "diamond"
                  ? "rotate(45deg)"
                  : "none",
            }}
          />
        )}


        {/* NAME */}

        <h1
          style={
            styles.cmsHeroHeading
          }
        >
          {cleanText(
            hero.name ||
            hero.heading ||
            "Welcome"
          )}
        </h1>


        {/* ROLE */}

        <h2
          style={
            styles.cmsHeroRole
          }
        >
          {cleanText(
            hero.role ||
            hero.subheading
          )}
        </h2>


        {/* TAGLINE */}

        <p
          style={
            styles.cmsHeroDescription
          }
        >
          {cleanText(
            hero.tagline ||
            hero.description
          )}
        </p>


        {/* BUTTONS */}

        {buttons.length > 0 && (

          <div
            style={
              styles.heroButtons
            }
          >

            {buttons.map(
              (button, index) => (

                <a
                  key={
                    button?._key ||
                    index
                  }
                  href={
                    button?.url ||
                    "#"
                  }
                  target={
                    button?.openInNewTab
                      ? "_blank"
                      : undefined
                  }
                  rel={
                    button?.openInNewTab
                      ? "noreferrer"
                      : undefined
                  }
                  style={{
                    ...styles.cmsButton,

                    background:
                      button?.variant ===
                      "outline"
                        ? "transparent"
                        : button
                            ?.backgroundColor ||
                          "#ffffff",

                    color:
                      button
                        ?.textColor ||
                      backgroundColor,

                    border:
                      button?.variant ===
                      "outline"
                        ? `2px solid ${
                            button?.borderColor ||
                            textColor
                          }`
                        : "none",
                  }}
                >
                  {cleanText(
                    button?.label ||
                    button?.text
                  )}
                </a>

              )
            )}

          </div>
        )}

      </div>

    </section>
  );
}


